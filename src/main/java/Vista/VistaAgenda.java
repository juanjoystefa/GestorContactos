    private void botonBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_botonBuscarActionPerformed
                             
        String nombre = nombreBuscar.getText();
        String telefono = controlador.buscarTelefono(nombre);

        if (telefono != null) {
            telefonoBuscar.setText(telefono);
        } else {
            telefonoBuscar.setText("No encontrado");
            JOptionPane.showMessageDialog(this, "Contacto no encontrado.", "Información", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_botonBuscarActionPerformed

    private void guardarContactoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_guardarContactoActionPerformed
        String nombre = nombreGuardar.getText();
        String telefono = telefonoGuardar.getText();

        if (controlador.agregarContacto(nombre, telefono)) {
            JOptionPane.showMessageDialog(this, "Contacto guardado exitosamente.");
            nombreGuardar.setText("");
            telefonoGuardar.setText("");
            nombreGuardar.requestFocus();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo guardar el contacto. Verifique los datos o si ya existe.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_guardarContactoActionPerformed

